// Translates the exported Postgres row-level security policies and table
// grants (db/source/pg-policies.json, pg-table-privs.json, pg-rls.json) into
// MySQL WHERE fragments for the data API: src/rest/policies.generated.json.
// Session variables replace auth.uid()/auth.jwt() (see migration 0003).
//   node tools/policies-to-mysql.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const source = name => JSON.parse(readFileSync(new URL(`../db/source/pg-${name}.json`, import.meta.url), 'utf8'));
const policies = source('policies'), privs = source('table-privs'), rls = source('rls');
const CASTS = ['text', 'uuid', 'integer', 'bigint', 'numeric', 'boolean', 'date', 'jsonb', 'json', 'timestamp with time zone',
  'character varying', 'account_status', 'user_role', 'job_status', 'job_type', 'application_status', 'connection_status', 'text\\[\\]'];

export function translate(expr) {
  if (!expr) return null;
  let e = expr;
  e = e.replace(/\(\s*SELECT auth\.uid\(\) AS uid\)/g, '@auth_uid').replace(/\bauth\.uid\(\)/g, '@auth_uid');
  e = e.replace(/\(\s*SELECT (?:public\.)?is_admin\(\) AS is_admin\)/g, '(@is_admin = 1)').replace(/\b(?:public\.)?is_admin\(\)/g, '(@is_admin = 1)');
  e = e.replace(/\bprivate\.actor_is_staff\(\)/g, '(@actor_is_staff = 1)');
  e = e.replace(/COALESCE\(\(\s*SELECT \(\(auth\.jwt\(\) -> 'app_metadata'::text\) ->> 'admin_role'::text\)\), ''::text\)/g, "COALESCE(@jwt_admin_role, '')");
  e = e.replace(/\(\(auth\.jwt\(\) -> 'app_metadata'::text\) ->> 'admin_role'::text\)/g, '@jwt_admin_role');
  e = e.replace(/\(\s*SELECT (app_role|app_account_active)\(\) AS \1\)/g, '$1()');
  e = e.replace(/\bprivate\.(admin_can|can_read_profile)\(/g, '$1(').replace(/\bpublic\.(owns_company|app_role|app_account_active)\(/g, '$1(');
  // Today's date in Baku (UTC+4 all year since 2016). DATE() matters: a
  // deadline of today must still compare as open.
  e = e.replace(/\(\(now\(\) AT TIME ZONE 'Asia\/Baku'::text\)\)::date/g, "DATE(CONVERT_TZ(UTC_TIMESTAMP(6), '+00:00', '+04:00'))");
  for (const cast of CASTS) e = e.replace(new RegExp(`::${cast}\\b`, 'g'), '');
  // x = ANY (ARRAY['a', 'b']) → x IN ('a', 'b')
  e = e.replace(/= ANY \(ARRAY\[((?:'(?:[^']|'')*'(?:, )?)+)\]\)/g, (_, list) =>
    `IN (${[...list.matchAll(/'((?:[^']|'')*)'/g)].map(m => `'${m[1]}'`).join(', ')})`);
  // value = ANY (array_column) → membership in the JSON array column
  e = e.replace(/(@auth_uid|'[^']*'|\(\w+(?:\.\w+)?\)|\w+(?:\.\w+)?) = ANY \((\w+(?:\.\w+)?)\)/g, 'JSON_CONTAINS($2, JSON_QUOTE($1))');
  e = e.replace(/\bIS NOT DISTINCT FROM\b/g, '<=>');
  e = e.replace(/\bnow\(\)/g, 'CURRENT_TIMESTAMP(6)');
  e = e.replace(/\bILIKE\b/g, 'LIKE');
  e = e.replace(/\bpublic\.(\w+)/g, '$1').replace(/\bprivate\.(\w+)\b(?!\()/g, 'private_$1');
  e = e.replace(/"(\w+)"/g, '`$1`');
  const unresolved = /::|\bANY\b|ARRAY\[|\bauth\.|->>|->|\bprivate\.|AT TIME ZONE/.test(e);
  return { sql: e, unresolved };
}

const tables = {};
const ensure = t => (tables[t] ||= { rls: false, grants: { anon: [], authenticated: [] }, policies: [] });
for (const r of rls) ensure(r.t).rls = r.rls;
for (const p of privs) if (p.s === 'public') ensure(p.t).grants[p.grantee] = p.privs.split(',').filter(x => ['SELECT', 'INSERT', 'UPDATE', 'DELETE'].includes(x));
const problems = [];
for (const p of policies) {
  const using = translate(p.qual), check = translate(p.with_check);
  if (using?.unresolved || check?.unresolved) problems.push(`${p.t}.${p.name}: ${(using?.unresolved ? using.sql : check.sql).slice(0, 200)}`);
  ensure(p.t).policies.push({
    name: p.name, cmd: p.cmd, permissive: p.permissive === 'PERMISSIVE',
    roles: p.roles.replace(/[{}]/g, '').split(',').filter(Boolean),
    using: using?.sql ?? null, check: check?.sql ?? null
  });
}
writeFileSync(new URL('../src/rest/policies.generated.json', import.meta.url), JSON.stringify({
  note: 'Generated by tools/policies-to-mysql.mjs from the Postgres RLS policies. Do not edit by hand.', tables
}, null, 1) + '\n');
console.log(`${Object.keys(tables).length} tables, ${policies.length} policies, ${problems.length} unresolved`);
for (const line of problems) console.log('  ' + line);
