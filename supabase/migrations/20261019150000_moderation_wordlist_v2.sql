-- Multilingual word-list layer for network moderation (v2).
-- Text is canonicalized before matching: NFKC (fullwidth/math letters), invisible and
-- combining characters removed, Cyrillic/Greek/Latin look-alikes and leetspeak folded
-- into per-script skeletons, separators dropped (s.i.k), repeats collapsed, masked
-- letters matched as wildcards (f*ck), spaced letters joined (s i k t i r) and short
-- split pairs joined (fu ck). Terms were curated from LDNOOBW V2 (CC0), censor-text
-- (Unlicense) and Persian-Swear-Words (Apache-2.0), checked against frequency lists of
-- nine languages (FrequencyWords, MIT; LocalDoc azerbaijani_words_frequency, MIT).
-- The functions mirror tools/modcanon.py; see tools/ for the curation pipeline.

-- Generated by tools/gen_sql.py from tools/modcanon.py; keep both in step.

create or replace function private.mod_prep(p text)
returns text language sql immutable parallel safe set search_path = '' as $$
  select regexp_replace(
           normalize(lower(regexp_replace(normalize(coalesce(p, ''), NFKC), E'[\u00AD\u034F\u061C\u115F\u1160\u17B4\u17B5\u180B-\u180F\u200B-\u200F\u202A-\u202E\u2060-\u206F\u3164\uFE00-\uFE0F\uFEFF\uFFA0\\U000E0000-\\U000E007F]', '', 'g')), NFD),
           E'[\u0300-\u036F\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]', '', 'g');
$$;

create or replace function private.mod_tokens(p text)
returns text[] language sql immutable parallel safe set search_path = '' as $$
  select coalesce(array_agg(t order by n) filter (where t <> ''), '{}')
  from (
    select regexp_replace(x, E'^[^a-z\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FE\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D\u0621-\u063A\u0641-\u064A\u0671-\u06D3\u03B1-\u03C90-9@$]+|[^a-z\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FE\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D\u0621-\u063A\u0641-\u064A\u0671-\u06D3\u03B1-\u03C90-9@$]+$', '', 'g') as t, n
    from regexp_split_to_table(private.mod_prep(p), E'[] \u0009\u000A\u000D\u000C\u000B\u00A0\u1680\u2000-\u200A\u2028\u2029\u202F\u205F\u3000,;:"()[{}/\\\\<>=\u00AB\u00BB\u201E\u201C\u201D''\u2018\u2019`\u00B4]+') with ordinality as u(x, n)
  ) s;
$$;

create or replace function private.mod_scripts(p_tok text)
returns text[] language sql immutable parallel safe set search_path = '' as $$
  select array_remove(array[
    case when p_tok ~ E'[a-z\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FE]' or p_tok ~ E'[\u03B1-\u03C9]'
           or not (p_tok ~ E'[\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D]' or p_tok ~ E'[\u0621-\u063A\u0641-\u064A\u0671-\u06D3]') then 'latin' end,
    case when p_tok ~ E'[\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D]' then 'cyrillic' end,
    case when p_tok ~ E'[\u0621-\u063A\u0641-\u064A\u0671-\u06D3]' then 'arabic' end], null);
$$;

create or replace function private.mod_map(p_tok text, p_script text)
returns text language sql immutable parallel safe set search_path = '' as $$
  select case p_script
    when 'latin' then translate(p_tok, E'\u0430\u0432\u0435\u043A\u043C\u043D\u043E\u0440\u0441\u0442\u0443\u0445\u0456\u0458\u0455\u04BB\u0501\u051B\u051D\u044C\u03B1\u03B2\u03B3\u03B5\u03B6\u03B7\u03B9\u03BA\u03BC\u03BD\u03BF\u03C1\u03C3\u03C2\u03C4\u03C5\u03C7\u03C901345789@$!|+\u20AC\u00A2\u00A9\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FElv', 'abekmhopctyxijshdqwbabyeznikuuopoctuxwoieastbgasiitecceiiodsaopiu')
    when 'cyrillic' then translate(p_tok, E'aceopxykmtbhi3046@\u044A\u0456\u0457\u0454\u0491', E'\u0430\u0441\u0435\u043E\u0440\u0445\u0443\u043A\u043C\u0442\u0432\u043D\u0438\u0437\u043E\u0447\u0431\u0430\u044C\u0438\u0438\u0435\u0433')
    else translate(p_tok, E'\u0623\u0625\u0622\u0671\u0649\u06CC\u06A9\u0629\u0624\u0626\u06C0\u06C1\u06BE', E'\u0627\u0627\u0627\u0627\u064A\u064A\u0643\u0647\u0648\u064A\u0647\u0647\u0647') end;
$$;

create or replace function private.mod_skel(p_tok text, p_script text)
returns text language sql immutable parallel safe set search_path = '' as $$
  select regexp_replace(
           regexp_replace(private.mod_map(p_tok, p_script),
             case p_script when 'latin' then '[^a-z]' when 'cyrillic' then E'[^\u0430-\u044F]' else E'[^\u0621-\u063A\u0641-\u064A\u0671-\u06D3]' end, '', 'g'),
           '(.)\1+', '\1', 'g');
$$;

-- Masked token (f*ck) as a regex with one '.' per hidden letter, or null.
create or replace function private.mod_mask(p_tok text, p_script text)
returns text language plpgsql immutable parallel safe set search_path = '' as $$
declare
  s text;
  v_letters integer;
  v_masks integer;
begin
  if p_tok !~ E'[a-z\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FE\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D\u0621-\u063A\u0641-\u064A\u0671-\u06D3\u03B1-\u03C90-9@$][*#%?_\u2022\u00B7]+[a-z\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FE\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D\u0621-\u063A\u0641-\u064A\u0671-\u06D3\u03B1-\u03C90-9@$]|[a-z\u0259\u0131\u0142\u00F8\u0111\u00DF\u00E6\u0153\u00FE\u0430-\u044F\u0456\u0457\u0454\u0491\u045E\u0455\u0458\u04BB\u0501\u051B\u051D\u0621-\u063A\u0641-\u064A\u0671-\u06D3\u03B1-\u03C90-9@$][*#%?_\u2022\u00B7]+$' then return null; end if;
  s := private.mod_map(translate(p_tok, E'*#%?_\u2022\u00B7', E'\u00B7\u00B7\u00B7\u00B7\u00B7\u00B7\u00B7'), p_script);
  s := regexp_replace(s, case p_script when 'latin' then E'[^a-z\u00B7]' when 'cyrillic' then E'[^\u0430-\u044F\u00B7]' else E'[^\u0621-\u063A\u0641-\u064A\u0671-\u06D3\u00B7]' end, '', 'g');
  s := regexp_replace(s, E'([^\u00B7])\\1+', '\1', 'g');
  v_masks := length(s) - length(replace(s, E'\u00B7', ''));
  v_letters := length(s) - v_masks;
  if v_letters < 2 or v_masks < 1 or v_masks > v_letters then return null; end if;
  return replace(s, E'\u00B7', '.');
end $$;

-- Every candidate the matcher checks: token skeletons, masked patterns,
-- runs of 3+ single letters ("s i k t i r") and short pairs ("fu ck").
create or replace function private.mod_candidates(p text)
returns table(script text, cand text, kind text)
language plpgsql immutable parallel safe set search_path = '' as $$
declare
  toks text[] := private.mod_tokens(p);
  n integer := coalesce(array_length(toks, 1), 0);
  sk jsonb := '{}';
  sc text;
  k text;
  pat text;
  run text;
  run_len integer;
  a text;
  b text;
begin
  for i in 1 .. n loop
    foreach sc in array private.mod_scripts(toks[i]) loop
      k := private.mod_skel(toks[i], sc);
      if k <> '' then
        script := sc; cand := k; kind := 'token'; return next;
        sk := jsonb_set(sk, array[sc], coalesce(sk -> sc, '{}') || jsonb_build_object(i::text, k), true);
      end if;
      pat := private.mod_mask(toks[i], sc);
      if pat is not null then
        script := sc; cand := pat; kind := 'mask'; return next;
      end if;
    end loop;
  end loop;

  foreach sc in array array['latin', 'cyrillic', 'arabic'] loop
    run := ''; run_len := 0;
    for i in 1 .. n + 1 loop
      k := sk -> sc ->> i::text;
      if k is not null and length(k) = 1 then
        run := run || k; run_len := run_len + 1;
        continue;
      end if;
      if run_len >= 3 then
        script := sc; cand := regexp_replace(run, '(.)\1+', '\1', 'g'); kind := 'run'; return next;
      end if;
      run := ''; run_len := 0;
    end loop;
    for i in 1 .. n - 1 loop
      a := sk -> sc ->> i::text;
      b := sk -> sc ->> (i + 1)::text;
      if a is not null and b is not null and greatest(length(a), length(b)) <= 4 then
        script := sc; cand := regexp_replace(a || b, '(.)\1+', '\1', 'g'); kind := 'bigram'; return next;
      end if;
    end loop;
  end loop;
end $$;

-- ' tok1 tok2 ... ' per script, for multi-word terms.
create or replace function private.mod_phrase_lines(p text)
returns table(script text, line text)
language sql immutable parallel safe set search_path = '' as $$
  select s.sc, ' ' || string_agg(s.k, ' ' order by s.n) || ' '
  from (
    select sc, private.mod_skel(t.tok, sc) as k, t.n
    from unnest(private.mod_tokens(p)) with ordinality as t(tok, n)
    cross join lateral unnest(private.mod_scripts(t.tok)) as sc
  ) s
  where s.k <> ''
  group by s.sc;
$$;

-- Canonical form of a term or allow-list word: (script, skeleton), phrases joined by spaces.
create or replace function private.mod_term(p text)
returns table(script text, term text)
language plpgsql immutable set search_path = '' as $$
declare
  toks text[] := private.mod_tokens(p);
  parts text[] := '{}';
  sc text[];
  s text;
begin
  if coalesce(array_length(toks, 1), 0) = 0 then return; end if;
  for i in 1 .. array_length(toks, 1) loop
    sc := private.mod_scripts(toks[i]);
    if array_length(sc, 1) <> 1 or (s is not null and sc[1] <> s) then return; end if;
    s := sc[1];
    parts := parts || private.mod_skel(toks[i], s);
  end loop;
  if '' = any(parts) then return; end if;
  script := s; term := array_to_string(parts, ' '); return next;
end $$;

