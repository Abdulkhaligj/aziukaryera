-- Terms and allowed words typed in the admin panel are stored as skeletons.
create or replace function private.moderation_terms_normalize()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_script text;
  v_term text;
begin
  select t.script, t.term into v_script, v_term
  from private.mod_term(case when tg_table_name = 'moderation_allow' then new.word else new.term end) t;
  if v_term is null then
    raise exception 'Söz tanınmadı: bir əlifbada yazılmış söz və ya söz birləşməsi əlavə edin' using errcode = 'check_violation';
  end if;
  if tg_table_name = 'moderation_allow' then
    new.word := v_term;
  else
    new.term := v_term;
  end if;
  new.script := v_script;
  return new;
end $$;

drop trigger if exists moderation_terms_normalize on public.moderation_terms;
create trigger moderation_terms_normalize before insert or update of term on public.moderation_terms
  for each row execute function private.moderation_terms_normalize();
drop trigger if exists moderation_allow_normalize on public.moderation_allow;
create trigger moderation_allow_normalize before insert or update of word on public.moderation_allow
  for each row execute function private.moderation_terms_normalize();

