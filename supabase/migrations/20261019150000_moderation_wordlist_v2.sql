create or replace function private.moderation_blocked_term(p_text text)
returns text language plpgsql stable security definer set search_path = '' as $$
declare
  v_hit text;
begin
  if coalesce(p_text, '') = '' then return null; end if;
  -- Middle finger emoji, with or without a skin tone.
  if strpos(p_text, E'\U0001F595') > 0 then return E'\U0001F595'; end if;

  with c as materialized (
    select * from private.mod_candidates(p_text) c
    where not exists (select 1 from public.moderation_allow a where a.script = c.script and a.word = c.cand)
  )
  select coalesce(
    -- whole words, and short split pairs of curated terms
    (select t.term from c join public.moderation_terms t on t.term = c.cand and t.active
      where (c.kind in ('token', 'run') and t.match = 'word') or (c.kind = 'bigram' and t.tier = 'A')
      limit 1),
    -- word starts with a stem
    (select t.term from c cross join lateral generate_series(3, length(c.cand)) g(n)
       join public.moderation_terms t on t.term = left(c.cand, g.n) and t.active and t.match in ('stem', 'infix')
      where c.kind in ('token', 'run')
      limit 1),
    -- root anywhere in the word
    (select t.term from c join public.moderation_terms t
         on t.active and t.match = 'infix' and t.script = c.script and strpos(c.cand, t.term) > 0
      where c.kind in ('token', 'run')
      limit 1),
    -- masked letters: f*ck, s*kt*r, х*й
    (select t.term from c join public.moderation_terms t
         on t.active and t.script = c.script and strpos(t.term, ' ') = 0
      where c.kind = 'mask'
        and ((t.match = 'word' and length(t.term) = length(c.cand) and t.term ~ ('^' || c.cand || '$'))
          or (t.match <> 'word' and length(t.term) <= length(c.cand) and t.term ~ ('^' || left(c.cand, length(t.term)) || '$')))
      limit 1),
    -- multi-word terms: amına koy, it oğlu, kos nane
    (select t.term from private.mod_phrase_lines(p_text) l join public.moderation_terms t
         on t.active and t.script = l.script and strpos(t.term, ' ') > 0
        and strpos(l.line, ' ' || t.term || case when t.match = 'word' then ' ' else '' end) > 0
      limit 1)
  ) into v_hit;
  return v_hit;
end $$;

